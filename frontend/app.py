def get_http_metrics():
    """Fetch live, persisted API monitoring summaries."""
    response = requests.get(f"{API_URL}/metrics", headers=api_headers(), timeout=20)
    response.raise_for_status()
    return response.json()


def get_drift_metrics():
    """Read offline PSI/KS, live monitoring sufficiency and alert rules."""
    response = requests.get(f"{API_URL}/monitoring/drift", headers=api_headers(), timeout=90)
    response.raise_for_status()
    return response.json()


def get_recommendations(basket):
    response = requests.post(
        f"{API_URL}/recommend",
        json={"basket": basket, "top_k": 5},
        headers=api_headers(),
        timeout=20,
    )
    response.raise_for_status()
    return response.json()


def predict_retention(customer_id):
    response = requests.post(
        f"{API_URL}/predict",
        json={"customer_id": customer_id},
        headers=api_headers(),
        timeout=20,
    )
    response.raise_for_status()
    return response.json()


def predict_what_if(customer_id, overrides):
    response = requests.post(
        f"{API_URL}/predict/what-if",
        json={"customer_id": customer_id, **overrides},
        headers=api_headers(),
        timeout=20,
    )
    response.raise_for_status()
    return response.json()


def stream_assistant(question, provider):
    """Yield SSE events from the API without buffering the complete response."""
    with requests.post(
        f"{API_URL}/chat/stream",
        json={"question": question, "provider": provider},
        headers={**api_headers(), "Accept": "text/event-stream"},
        stream=True,
        timeout=(10, 120),
    ) as response:
        response.raise_for_status()
        event_name = None
        data_lines = []

        def parse_event(name, parts):
            if not name or not parts:
                return None
            return name, json.loads("\n".join(parts))

        for raw_line in response.iter_lines(decode_unicode=False):
            line = raw_line.decode("utf-8") if isinstance(raw_line, bytes) else raw_line
            if not line:
                event = parse_event(event_name, data_lines)
                if event is not None:
                    yield event
                event_name = None
                data_lines = []
            elif line.startswith("event:"):
                event_name = line[6:].strip()
            elif line.startswith("data:"):
                data_lines.append(line[5:].lstrip(" "))

        event = parse_event(event_name, data_lines)
        if event is not None:
            yield event


